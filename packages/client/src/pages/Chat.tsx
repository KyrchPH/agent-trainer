  async function handleSuggestionEditSave(
    assistantMessageId: number,
    suggestionId: number
  ) {
    if (!name) return;
    const draft = editingSuggestion[suggestionId];
    if (draft === undefined) return;
    const trimmed = draft.trim();
    if (!trimmed) return;

    // Snapshot the previous state so we can roll back on failure.
    const previousRow = (suggestionsByMessage[assistantMessageId] ?? []).find(
      s => s.id === suggestionId
    );

    // Optimistic update: replace text AND clear vote tallies, since the
    // server wipes `suggestion_votes` for this row as part of the edit.
    setSuggestionsByMessage(prev => {
      const updated = (prev[assistantMessageId] ?? []).map(s =>
        s.id === suggestionId
          ? { ...s, answer: trimmed, upvotes: 0, downvotes: 0, my_vote: null }
          : s
      );
      return { ...prev, [assistantMessageId]: updated };
    });
    handleSuggestionEditCancel(suggestionId);

    try {
      await api.editSuggestion(suggestionId, trimmed, name);
    } catch (err) {
      console.error('Edit suggestion failed:', err);
      // Roll back to the previous text + tallies, and reopen the editor
      // with the failed draft so the user can retry.
      if (previousRow) {
        setSuggestionsByMessage(prev => {
          const reverted = (prev[assistantMessageId] ?? []).map(s =>
            s.id === suggestionId ? previousRow : s
          );
          return { ...prev, [assistantMessageId]: reverted };
        });
      }
      setEditingSuggestion(prev => ({ ...prev, [suggestionId]: trimmed }));
    }
  }

  async function toggleSuggestions(assistantIdx: number) {
    const msg = messages[assistantIdx];
    if (!msg.id) return;
    const messageId = msg.id;

    // Collapse if already open.
    if (openSuggestionsFor.has(messageId)) {
      setOpenSuggestionsFor(prev => {
        const next = new Set(prev);
        next.delete(messageId);
        return next;
      });
      return;
    }

    // Open immediately; fetch (or refetch) so the list reflects any new
    // suggestions submitted since the last expansion.
    setOpenSuggestionsFor(prev => {
      const next = new Set(prev);
      next.add(messageId);
      return next;
    });

    const question = findPrecedingQuestion(assistantIdx);
    if (!question) return;

    setLoadingSuggestionsFor(prev => {
      const next = new Set(prev);
      next.add(messageId);
      return next;
    });
    try {
      const { suggestions } = await api.getSuggestions(question, name);
      setSuggestionsByMessage(prev => ({ ...prev, [messageId]: suggestions }));
    } catch (err) {
      console.error('Failed to load suggestions:', err);
      setSuggestionsByMessage(prev => ({ ...prev, [messageId]: [] }));
    } finally {
      setLoadingSuggestionsFor(prev => {
        const next = new Set(prev);
        next.delete(messageId);
        return next;
      });
    }
  }

