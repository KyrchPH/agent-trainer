// Page size for the chat-history lazy loader. Matches the server's default
// when no explicit `limit` is passed.
const MESSAGES_PAGE_SIZE = 30;
// When the user scrolls within this many pixels of the top, trigger a fetch
// of the next older page (if any remain). 100px gives a smooth experience.
// The prepend happens before they reach scrollTop=0 and "stick" at the edge.
const LAZY_LOAD_THRESHOLD_PX = 100;

// Server row -> in-component message shape. Used by both the initial fetch
// and the lazy loader. `from_qa_entries` is coerced to a strict boolean
// because MySQL returns TINYINT(1) as 0/1; `suggestion_count` is forced
// numeric because of similar string-vs-number quirks across drivers.
function storedToMessage(m: StoredMessage): Message {
  return {
    id: m.id,
    role: m.role,
    content: m.content,
    my_vote: m.my_vote,
    suggestion_count: Number(m.suggestion_count ?? 0),
    from_qa_entries: Boolean(m.from_qa_entries)
  };
}

type VoteState = 'up' | 'down' | null;
// 'system' is a client-only role used to render command output (like the
// `/users` list). System messages are never sent to the server or persisted;
// they disappear on reload.
type MessageRole = 'user' | 'assistant' | 'system';

interface SlashCommand {
  name: string;            // including the leading slash, e.g. "/restart"
  description: string;     // shown in the dropdown
}

const SLASH_COMMANDS: SlashCommand[] = [
  { name: '/restart',        description: 'Deletes all the conversations of the account.' },
  { name: '/clear-votes',    description: 'Clears all your votes on all messages.' },
  { name: '/clean',          description: 'Clears the visible messages on this device only. Data in the database is untouched; messages return on reload.' },
  { name: '/delete-account', description: 'Deletes the account and all associated data, then returns to the name prompt.' },
  { name: '/users',          description: 'Lists all existing users.' }
];

interface Message {
  id?: number;
  role: MessageRole;
  content: string;
  my_vote?: VoteState;
  // Number of rows in the `suggestions` table for this assistant message's
  // preceding user question. Used to gate the "See other suggestions" button:
  // it's only shown when count > 1 (i.e. there are multiple alternatives to
  // browse). Undefined / 0 for user bubbles.
  suggestion_count?: number;
  // True when this assistant message's content matches the current
  // qa_entries answer for its preceding user question — i.e. it was served
  // from the trained library, not freshly generated by the LLM. Used to
  // render the yellow "Preferred" badge above the bubble.
  from_qa_entries?: boolean;
}

