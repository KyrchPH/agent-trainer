  async function executeCommand(cmd: string) {
    if (!name) return;
    setInput('');
    setLoading(true);
    try {
      switch (cmd) {
        case '/restart': {
          if (!window.confirm('Delete every conversation under your account? This cannot be undone.')) return;
          const { deleted_messages } = await api.clearMessages(name);
          setMessages([]);
          appendSystem(`Deleted ${deleted_messages} message${deleted_messages === 1 ? '' : 's'} from your account.`);
          break;
        }
        case '/clear-votes': {
          if (!window.confirm('Clear all of your up/down votes on every message?')) return;
          const { deleted_votes } = await api.clearVotes(name);
          setMessages(prev =>
            prev.map(m => (m.role === 'assistant' ? { ...m, my_vote: null } : m))
          );
          appendSystem(`Cleared ${deleted_votes} vote${deleted_votes === 1 ? '' : 's'}.`);
          break;
        }
        case '/clean': {
          // Pure client wipe — does not touch the server.
          setMessages([]);
          break;
        }
        case '/delete-account': {
          if (!window.confirm('Permanently delete your account and all associated data?')) return;
          await api.deleteAccount(name);
          clearName(); // sends the user back to the name prompt
          break;
        }
        case '/users': {
          const { users } = await api.listUsers();
          const body =
            users.length === 0
              ? 'No users yet.'
              : `Users (${users.length}):\n${users.map(u => `- ${u}`).join('\n')}`;
          appendSystem(body);
          break;
        }
        default:
          appendSystem(`Unknown command: ${cmd}`);
      }
    } catch (err) {
      appendSystem(`Command failed: ${(err as Error).message}`);
    } finally {
      setLoading(false);
    }
  }

  async function handleCopy(messageIdx: number, content: string) {
    try {
      if (navigator.clipboard?.writeText) {
        await navigator.clipboard.writeText(content);
      } else {
        // Fallback for non-secure contexts (e.g. http://) where the Clipboard
        // API is unavailable.
        const ta = document.createElement('textarea');
        ta.value = content;
        ta.setAttribute('readonly', '');
        ta.style.position = 'fixed';
        ta.style.opacity = '0';
        document.body.appendChild(ta);
        ta.select();
        document.execCommand('copy');
        document.body.removeChild(ta);
      }
      setCopiedIdx(messageIdx);
      if (copyResetTimerRef.current !== null) {
        window.clearTimeout(copyResetTimerRef.current);
      }
      copyResetTimerRef.current = window.setTimeout(() => {
        setCopiedIdx(curr => (curr === messageIdx ? null : curr));
        copyResetTimerRef.current = null;
      }, 1500);
    } catch (err) {
      console.error('Copy failed:', err);
    }
  }

  async function handleVote(messageIdx: number, voteType: 'up' | 'down') {
    if (!name) return;
    const msg = messages[messageIdx];
    if (!msg.id) return;

    const previous = msg.my_vote ?? null;
    const next: VoteState = previous === voteType ? null : voteType;

    // Trigger the pop animation only when activating a vote (not when clearing).
    if (next !== null) {
      const key = Date.now();
      setAnimTrigger({ messageId: msg.id, voteType: next, key });
      window.setTimeout(() => {
        setAnimTrigger(curr => (curr?.key === key ? null : curr));
      }, 400);
    }

    // Optimistic update.
    setMessages(prev =>
      prev.map((m, i) => (i === messageIdx ? { ...m, my_vote: next } : m))
    );

    try {
      await api.voteOnMessage(msg.id, name, next);
    } catch (err) {
      // Revert on failure.
      setMessages(prev =>
        prev.map((m, i) => (i === messageIdx ? { ...m, my_vote: previous } : m))
      );
      console.error('Vote failed:', err);
    }
  }

  async function submit() {
    if (!input.trim() || loading || !name) return;

    // Slash command intercept: a bare command (no extra text) routes to the
    // command handler instead of the chat / suggestion flow. Anything that
    // starts with `/` but isn't a known command falls into the unknown-command
    // branch (rather than being sent to the LLM) so users don't accidentally
    // train the agent on typo'd commands.
    const trimmed = input.trim();
    if (!replyTo && trimmed.startsWith('/')) {
      const cmd = SLASH_COMMANDS.find(c => c.name === trimmed.toLowerCase());
      if (cmd) {
        await executeCommand(cmd.name);
      } else {
        setInput('');
        appendSystem(`Unknown command: ${trimmed}. Type / to see available commands.`);
      }
      return;
    }

    if (replyTo) {
      const suggested = input.trim();
      const { question, assistantMessageId } = replyTo;
      setInput('');
      setLoading(true);
      try {
        const result = await api.suggestAnswer(question, suggested, name, assistantMessageId);
        setReplyTo(null);
        // The server runs promoteWinningSuggestion after every suggestion;
        // when the result is `{ promoted: true, current_answer: suggested }`,
        // our submission is now the canonical qa_entries answer for this
        // question. We also passed `target_message_id` to the server so it
        // rewrote that specific bubble's row in `messages`. Mirror the same
        // update locally: replace ONLY the targeted bubble's content + flip
        // its Preferred flag, and bump suggestion_count on every matching
        // bubble for the question. (When the suggestion didn't win — e.g.
        // existing votes outweighed it — we just bump the count.)
        const wonPromotion = result.promoted && result.current_answer === suggested;
        setMessages(prev => {
          const next = prev.map((m, i) => {
            if (m.role !== 'assistant') return m;
            // Walk backwards to find the preceding user question for this bubble.
            let prevQ: string | null = null;
            for (let j = i - 1; j >= 0; j--) {
              if (prev[j].role === 'user') {
                prevQ = prev[j].content;
                break;
              }
            }
            if (prevQ !== question) return m;
            const isTargetedBubble =
              wonPromotion && assistantMessageId !== null && m.id === assistantMessageId;
            return {
              ...m,
              content: isTargetedBubble ? suggested : m.content,
              from_qa_entries: isTargetedBubble ? true : m.from_qa_entries,
              suggestion_count: (m.suggestion_count ?? 0) + 1
            };
          });
          return next;
        });
        // If this question already has an open suggestions panel anywhere,
        // drop its cached list so the next open re-fetches and shows the
        // submission we just made.
        setSuggestionsByMessage(prev => {
          const next: typeof prev = {};
          for (const [k, v] of Object.entries(prev)) {
            const id = Number(k);
            // Conservative: clear all caches; the panel will refetch on next open.
            // (A precise filter would require re-walking messages to map id -> question.)
            void v;
            void id;
          }
          return next;
        });
        setSuggestStatus(
          result.promoted
            ? 'Your suggestion is now the saved answer.'
            : 'Suggestion submitted. The highest-voted suggestion wins.'
        );
        setTimeout(() => setSuggestStatus(null), 4000);
      } catch (err) {
        setSuggestStatus('Error: ' + (err as Error).message);
        setTimeout(() => setSuggestStatus(null), 6000);
      } finally {
        setLoading(false);
      }
      return;
    }

    const question = input.trim();
    setInput('');
    setMessages(prev => [...prev, { role: 'user', content: question }]);
    setLoading(true);
    try {
      const res = await api.chat(question, name);
      const reply = res.answer ?? 'No response.';
      setMessages(prev => {
        // Patch the last user bubble with its id (from server) and append the assistant.
        const patched = [...prev];
        const lastUserIdx = patched.length - 1;
        if (
          lastUserIdx >= 0 &&
          patched[lastUserIdx].role === 'user' &&
          patched[lastUserIdx].id === undefined &&
          res.user_message_id !== undefined
        ) {
          patched[lastUserIdx] = { ...patched[lastUserIdx], id: res.user_message_id };
        }
        patched.push({
          id: res.assistant_message_id,
          role: 'assistant',
          content: reply,
          my_vote: null,
          suggestion_count: Number(res.suggestion_count ?? 0),
          from_qa_entries: Boolean(res.from_qa_entries)
        });
        return patched;
      });
    } catch (err) {
      setMessages(prev => [
        ...prev,
        { role: 'assistant', content: 'Error: ' + (err as Error).message }
      ]);
    } finally {
      setLoading(false);
    }
  }

